_XOR_ADD = (0, 3, 4, 7, 8, 11, 12, 15)  # positions that use xor-then-add; the rest use add-then-xor
_PERM = (8, 11, 12, 15, 2, 1, 6, 5, 10, 9, 14, 13, 0, 7, 4, 3)


def _mix(t):
    for k in range(0, 16, 2):
        e = ((t[k] << 1) + t[k + 1]) & 255
        t[k + 1] = (t[k] + t[k + 1]) & 255
        t[k] = e


def _perm(t):
    e = t[:16]
    for k in range(16):
        t[k] = e[_PERM[k]]


def _rot3(t):
    for k in range(17):
        t[k] = ((t[k] << 3) & 255) + (t[k] >> 5) & 255


def _schedule(key):
    m = [[0] * 16 for _ in range(17)]
    i = list(key) + [0]
    for k in range(16):
        i[16] ^= i[k]
    r = i[:]
    m[0] = i[:16]
    for h in range(16):
        _rot3(r)
        s = h + 1
        for c in range(16):
            m[h + 1][c] = (r[s] + _A[h + 1][15 - c]) & 255
            s += 1
            if s > 16:
                s = 0
    return m


def _round(n, c, m):
    for u in range(16):
        c[u] = c[u] ^ m[2 * n][u] if u in _XOR_ADD else (c[u] + m[2 * n][u]) & 255
    for u in range(16):
        c[u] = _S[c[u]] if u in _XOR_ADD else _I[c[u]]
    for u in range(16):
        c[u] = (c[u] + m[2 * n + 1][u]) & 255 if u in _XOR_ADD else c[u] ^ m[2 * n + 1][u]
    for _ in range(3):
        _mix(c)
        _perm(c)
    _mix(c)


def _encrypt(t, m, feed_forward):
    s = t[:16]
    for r in range(8):
        if r == 2 and feed_forward:
            for h in range(16):
                t[h] = s[h] ^ t[h] if h in _XOR_ADD else (s[h] + t[h]) & 255
        _round(r, t, m)
    for h in range(16):
        t[h] = t[h] ^ m[16][h] if h in _XOR_ADD else (t[h] + m[16][h]) & 255


def respond(challenge):
    """Answer a 16-byte challenge; returns the 17-byte reply (0x01 + 16 bytes)."""
    rnd = list(challenge)
    key = LINK_KEY
    rep = [SEED[k % len(SEED)] for k in range(16)]
    out = rnd[:]
    m = _schedule(key)
    _encrypt(out, m, False)
    for k in range(16):
        out[k] = ((out[k] ^ rnd[k]) + rep[k]) & 255
    h = [0] * 16
    for k in range(16):
        add = k % 2 == 0 if k < 8 else k % 2 == 1
        const = (233, 229, 223, 193, 179, 167, 149, 131)[k % 8]
        h[k] = (key[k] + const) & 255 if add else const ^ key[k]
    _encrypt(out, _schedule(h), True)
    return bytes([1] + out)


